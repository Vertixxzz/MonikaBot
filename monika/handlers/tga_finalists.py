"""Берлога Awards, этап 2: шорт-лист для голосования.

Номер номинации = её место в TGA_FINAL (с 1)  -> tga_votes.nomination
Номер финалиста = его место в списке (с 0)    -> tga_votes.choice

Поэтому ПОСЛЕ старта голосования финалистов не переставлять и не удалять,
иначе старые голоса уедут на других людей. Тексты (имена, описания, опечатки)
править можно спокойно, новых финалистов — только дописывать в конец списка.
"""
from __future__ import annotations

from typing import NamedTuple


class Finalist(NamedTuple):
    name: str        # имя или название: «Слава», «Danganronpa»
    tag: str = ""    # ник(и): «@Shifrilshik»; пусто для игр, событий, цитат
    note: str = ""   # пояснение — показывается в тексте сообщения, не на кнопке

    @property
    def label(self) -> str:
        """Как на кнопке и в выгрузке: «имя - @ник»."""
        return f"{self.name} - {self.tag}" if self.tag else self.name


class Nomination(NamedTuple):
    section: str
    title: str
    desc: str
    finalists: tuple[Finalist, ...]


