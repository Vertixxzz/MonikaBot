from aiogram import Router, F
from aiogram.types import Message

router = Router()

@router.message(lambda msg: msg.text and msg.text.lower().startswith("/help"))
async def handle_help(message: Message):
    await message.reply(
        """*Всем привет!*
Я - _Моника_, ваш чат-менеджер по любым вопросам, проблемам и хаосу в чате.  
Если вы где-то запутались, не знаете команду или кто-то нарушает правила - просто зовите меня :)

Вот что я умею:

---

*1. Модерация* 
Я слежу за порядком, но стараюсь быть справедливой!

Команды:
`мут`  
`размут`  
`бан`  
`кик`  
`варн`

Можно использовать *двумя способами:*
- *реплаем* на сообщение (самый удобный вариант)
- через @юзера

Примеры:
`бан` (реплаем на сообщение)  
`мут @user 10м`  
`бан @user 7д`  
`кик @user`

Причина и время *не обязательны*. Если время не указано - мут будет вечным.

---

*2. Варны*  
`варн` - выдать предупреждение.

Варны:
- автоматически снимаются, когда срок заканчивается
- если варнов становится 3 - пользователь автоматически банится, и счетчик сбрасывается

---

*3. Погода*  
Хочется свежей правды, а не фантазий? ну вот и отлично.

`погода <город>`  
Также работает: `Моника погода <город>` (если так привычнее)

---

*4. Ваш день*  
`мой день` - расскажу, как пройдет ваш сегодняшний день.  
У меня много вариантов, так что скучно не будет

---

*5. Статистика*  
`стата/статистика` - покажу вашу статистику.

---

*6. Память (обычная)*  
`Моника запомни <ваш текст>` - я сохраню то, что вы попросите.  
`Моника совет` - выдам случайную фразу/совет из сохраненного.

---

*7. ИИ и СуперПамять (для бусти/разработчиков)*  
Пока это доступно только разработчикам и тем, кто покупал бусти за последние 3 месяца.

Команды:
`Моника ии <текст>` - отвечаю, используя ваш контекст и суперпамять  
`Моника суперзапомни <текст>` - запоминаю важное для будущих ответов

Важно:
_Суперпамять я использую только если для этого есть весомая причина._

---

*8. Профиля и администрация*  
Иногда важно понимать кто тут главный, а кто просто делает вид.

Команды:
`кто админ`  
`кто модер`

Админские команды:
`повысить <число>`  
`понизить <число>`  
`разжаловать`  
`увольняюсь` / `ухожу в отставку`  
`восстановить права` - если создатель чата остался без прав

---

Спасибо что вы с нами 
И да - я все вижу. абсолютно все.
""",
        parse_mode="Markdown"
    )
